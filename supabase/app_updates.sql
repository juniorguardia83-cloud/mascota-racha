create table if not exists public.app_updates (
  id bigint generated by default as identity primary key,
  version_code integer not null unique,
  version_name text not null,
  title text not null default 'Novedades de MimoPets',
  notes text not null default '',
  apk_url text not null,
  is_published boolean not null default true,
  published_at timestamptz not null default now()
);
alter table public.app_updates enable row level security;
drop policy if exists "Los usuarios pueden consultar actualizaciones publicadas" on public.app_updates;
create policy "Los usuarios pueden consultar actualizaciones publicadas"
on public.app_updates for select to authenticated using (is_published = true);
